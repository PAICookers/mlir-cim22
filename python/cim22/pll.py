def select_pll_clock(frequency_mhz: float) -> PLLClockSetting:
    """Look up a listed target MHz; warn only for rows marked "maybe available".

    Unlisted targets raise ValueError. Neither serial commands nor nearest
    frequencies are calculated at runtime.
    """
    setting = next(
        (
            row
            for row in PLL_CLOCK_TABLE
            if row.target_frequency_mhz == frequency_mhz
        ),
        None,
    )
    if setting is None:
        raise ValueError(
            "clock_frequency_mhz is not a listed target in PLL_CLOCK_TABLE "
            "(199 presets, 15.75–1000 MHz); select a table entry"
        )
    if setting.status == "maybe available":
        warnings.warn(
            f"PLL table marks target {frequency_mhz:g} MHz as maybe available"
            f": hardware operation may be unstable; actual table "
            f"frequency {setting.actual_frequency_mhz:g} MHz, "
            f"serial {setting.serial_hex}",
            RuntimeWarning,
            stacklevel=2,
        )
    return setting
